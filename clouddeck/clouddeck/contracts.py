"""Stable contracts between CloudDeck's control plane and execution adapters."""

from __future__ import annotations

from typing import Any, Protocol


class SessionProvider(Protocol):
    """A machine/session backend that can host a remote desktop."""

    provider_id: str
    session_id: int | None
    profiles: dict[str, dict[str, Any]]

    def status(self) -> dict[str, Any]: ...
    def start(self, profile_id: str) -> dict[str, Any]: ...
    def stop(self) -> dict[str, Any]: ...
    def restart(self, profile_id: str) -> dict[str, Any]: ...
    def launch_app(self, app_id: str) -> dict[str, Any]: ...
    def set_keys(self, requested: list[str]) -> dict[str, Any]: ...
    def heartbeat(self) -> dict[str, Any]: ...
    def pointer(self, dx: int, dy: int, button: str | None = None, scroll_y: int = 0) -> dict[str, Any]: ...
    def release_all(self) -> None: ...
    def metrics(self) -> dict[str, Any]: ...


class StreamTransport(Protocol):
    """A browser/native transport used to carry video, audio and input."""

    transport_id: str

    def viewer_path(self) -> str: ...
    def capabilities(self) -> dict[str, bool]: ...
